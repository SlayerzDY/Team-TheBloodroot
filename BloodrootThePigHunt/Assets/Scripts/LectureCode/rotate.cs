using UnityEngine;
using System.Collections;
//==============================================================================================
// Declare Rotate
//==============================================================================================
public class rotate : MonoBehaviour
{
    //==========================================================================================
    // Declare Variables
    //==========================================================================================
    [SerializeField] int speed;
    //==========================================================================================
    // Declare Public Functions
    //==========================================================================================
    // Function, Update
    //------------------------------------------------------------------------------------------
    void Update()
    {
        transform.Rotate(Vector3.up, speed * Time.deltaTime);
    }
    //==========================================================================================
}
//==============================================================================================
// End of Rotate CS
//==============================================================================================